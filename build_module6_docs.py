def validate_doc(path: Path) -> tuple[int, int, int]:
    doc = Document(path)
    paragraphs = sum(1 for p in doc.paragraphs if p.text.strip())
    tables = len(doc.tables)
    words = sum(len(p.text.split()) for p in doc.paragraphs)
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                words += sum(len(p.text.split()) for p in cell.paragraphs)
    if paragraphs < 45 or tables < 10 or words < 2500:
        raise RuntimeError(f'Validation failed for {path.name}: paragraphs={paragraphs}, tables={tables}, words={words}')
    return paragraphs, tables, words


